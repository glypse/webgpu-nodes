// Archives the current version of every standard-library file, then lists
// the archive in versions/index.ts. Run after changing a library file.
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { libraryRef, standardLibrary } from "../src/library";

const libraryDir = join(import.meta.dirname, "../src/library");
const versionsDir = join(libraryDir, "versions");

for (const entry of standardLibrary) {
	const dir = join(versionsDir, entry.id);
	mkdirSync(dir, { recursive: true });
	const source = readFileSync(join(libraryDir, `${entry.id}.json`), "utf8");
	writeFileSync(join(dir, `${entry.version}.json`), source);
}

const lines: string[] = [];
for (const id of readdirSync(versionsDir, { withFileTypes: true })) {
	if (!id.isDirectory()) continue;
	for (const file of readdirSync(join(versionsDir, id.name)).toSorted()) {
		const version = file.replace(/\.json$/, "");
		const ref = libraryRef(id.name, version);
		lines.push(`\t"${ref}": () => import("./${id.name}/${file}").then((m) => m.default),`);
	}
}

writeFileSync(
	join(versionsDir, "index.ts"),
	`// Generated by scripts/archive-stdlib.ts.

/** Every archived standard-library version, by ref, loaded on demand. */
export const archivedVersions: Record<string, () => Promise<unknown>> = {
${lines.join("\n")}
};
`,
);
